"""One-off build helper: vendor the latin subset of the project fonts.

Run during development only (`python3 tools/fetch_fonts.py`); the resulting
woff2 files are committed so the app never performs a network request.
Google Fonts serves Inter and JetBrains Mono as variable fonts, so one latin
file per family covers every weight through the wght axis.
"""

from __future__ import annotations

import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "static" / "fonts"
CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Inter:wght@400;500;700&family=JetBrains+Mono:wght@400;600;700&display=swap"
)
UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

# family -> (file stem, wght axis range supported by the variable font)
FAMILIES = {
    "Inter": ("inter", "100 900"),
    "JetBrains Mono": ("jetbrains-mono", "100 800"),
}


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def main() -> None:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    for stale in FONT_DIR.glob("*.woff2"):
        stale.unlink()

    css = fetch(CSS_URL).decode("utf-8")
    blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
    seen: set[str] = set()
    faces: list[str] = []

    for subset, block in blocks:
        if subset != "latin":
            continue
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        if family in seen or family not in FAMILIES:
            continue
        seen.add(family)
        stem, weight_range = FAMILIES[family]
        url = re.search(r"url\((https://[^)]+)\)", block).group(1)
        filename = f"{stem}-latin.woff2"
        (FONT_DIR / filename).write_bytes(fetch(url))
        faces.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight_range};\n"
            "  font-display: swap;\n"
            f"  src: url('/static/fonts/{filename}') format('woff2');\n"
            "}\n"
        )
        print("vendored", filename)

    header = (
        "/* Self-hosted font subsets. Generated by tools/fetch_fonts.py and\n"
        "   committed, so the app serves its own type and makes no outbound\n"
        "   network requests at runtime. */\n\n"
    )
    (ROOT / "static" / "fonts.css").write_text(header + "\n".join(faces), encoding="utf-8")


if __name__ == "__main__":
    main()
